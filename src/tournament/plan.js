// Turns a tournament format into stages and match drafts, and works out what can
// happen next. Pure functions: ids come from an injected idGen.
import { roundRobin, splitIntoGroups, knockoutFirstRound, knockoutNextRound, roundName, shuffled, avoidSameGroup } from "./fixtures";
import { matchOutcome, computeStandings } from "./standings";

const stageMatchIds = (stage) => stage.matchIds || [];

function draftsForRounds(rounds, stageLabel, idGen, groupName) {
  const drafts = [];
  rounds.forEach((round, ri) =>
    round.forEach((m) => drafts.push({ id: idGen("match"), teamAId: m.a, teamBId: m.b, stage: stageLabel, round: ri + 1, groupName: groupName || null }))
  );
  return drafts;
}

function knockoutStage(first, idGen, name) {
  const drafts = [];
  const entries = first.entries.map((e) => {
    if (e.type === "bye") return { type: "bye", teamId: e.teamId };
    const id = idGen("match");
    drafts.push({ id, teamAId: e.a, teamBId: e.b, stage: name, round: null, groupName: null });
    return { type: "match", matchId: id };
  });
  return { drafts, stage: { id: idGen("stage"), kind: "knockout", name, size: first.size, entries, matchIds: drafts.map((d) => d.id) } };
}

// ---------------------------------------------------------------------------
export function planFirstStage(tournament, { idGen, rng }) {
  const f = tournament.format;
  const ids = f.shuffle ? shuffled(tournament.teamIds, rng) : [...tournament.teamIds];

  if (f.type === "roundrobin") {
    const drafts = draftsForRounds(roundRobin(ids, f.legs), "League", idGen);
    return { stages: [{ id: idGen("stage"), kind: "league", name: "League", matchIds: drafts.map((d) => d.id) }], drafts, order: ids };
  }

  if (f.type === "knockout") {
    const first = knockoutFirstRound(ids);
    const { drafts, stage } = knockoutStage(first, idGen, roundName(first.size));
    return { stages: [stage], drafts, order: ids };
  }

  // groups + knockout: this creates the group stage; the knockout follows when it is complete
  const groups = splitIntoGroups(ids, f.groupCount);
  const stages = [];
  let drafts = [];
  groups.forEach((g) => {
    const d = draftsForRounds(roundRobin(g.teamIds, f.legs), g.name, idGen, g.name);
    drafts = drafts.concat(d);
    stages.push({ id: idGen("stage"), kind: "group", name: g.name, groupName: g.name, teamIds: g.teamIds, matchIds: d.map((x) => x.id) });
  });
  // play round 1 of every group first, then round 2, ...
  drafts.sort((x, y) => x.round - y.round || String(x.groupName).localeCompare(String(y.groupName)));
  return { stages, drafts, order: ids };
}

// ---------------------------------------------------------------------------
// The champion is decided by the FINAL only: a match of this tournament whose round is "Final"
// (generated by a knockout, or added by hand with Round: Final). Until that match is played and has
// a winner, nobody is champion, even if a team already leads the table.
function finalResult(tournament, byId) {
  const finals = (tournament.matchIds || [])
    .map((id) => byId.get(id))
    .filter((m) => m && String(m.stage || "").trim().toLowerCase() === "final");
  const outcomes = finals.map((m) => matchOutcome(m));
  const needsWinner = finals.filter((m, i) => outcomes[i].done && outcomes[i].decidedWinnerId === null).map((m) => m.id);
  let champion = null;
  let latest = "";
  finals.forEach((m, i) => {
    const w = outcomes[i].done ? outcomes[i].decidedWinnerId : null;
    if (w && String(m.date || "") >= latest) {
      champion = w;
      latest = String(m.date || "");
    }
  });
  return { hasFinal: finals.length > 0, needsWinner, champion };
}

export function tournamentProgress(tournament, matches) {
  const stages = tournament.stages || [];
  const byId = new Map(matches.map((m) => [m.id, m]));
  const fin = finalResult(tournament, byId);
  const empty = { hasStages: false, total: 0, completed: 0, allDone: false, needsWinner: fin.needsWinner, canAdvance: false, nextLabel: null, complete: !!fin.champion, champion: fin.champion, hasFinal: fin.hasFinal, leagueDone: false };
  if (!stages.length) return empty;

  const hasKnockout = stages.some((s) => s.kind === "knockout");
  const phase = hasKnockout ? [stages[stages.length - 1]] : stages;
  const ids = phase.flatMap(stageMatchIds);
  const ms = ids.map((id) => byId.get(id)).filter(Boolean);
  const outcomes = ms.map(matchOutcome);
  const completed = outcomes.filter((o) => o.done).length;
  const knockoutPhase = phase[0].kind === "knockout";
  const needsWinner = knockoutPhase ? ms.filter((m, i) => outcomes[i].done && outcomes[i].decidedWinnerId === null).map((m) => m.id) : [];
  const allDone = ms.length > 0 && completed === ms.length && needsWinner.length === 0;

  const out = { hasStages: true, total: ms.length, completed, allDone, needsWinner: [...new Set([...needsWinner, ...fin.needsWinner])], canAdvance: false, nextLabel: null, complete: false, champion: null, hasFinal: fin.hasFinal, leagueDone: false };

  if (tournament.format.type === "roundrobin") {
    // A league has no champion until a Final has been played. Topping the table is not enough.
    out.leagueDone = allDone;
    out.champion = fin.champion;
    out.complete = !!fin.champion;
    return out;
  }
  if (!knockoutPhase) {
    // group stage finished -> knockout can be generated
    if (allDone) {
      out.canAdvance = true;
      out.nextLabel = "Generate knockout stage";
    }
    out.champion = fin.champion; // a Final added by hand
    out.complete = !!fin.champion;
    return out;
  }
  const last = phase[0];
  if (allDone && last.size === 2) {
    out.complete = true;
    const m = byId.get(last.matchIds[0]);
    out.champion = matchOutcome(m).decidedWinnerId;
    out.complete = !!out.champion;
  } else if (allDone) {
    out.canAdvance = true;
    out.nextLabel = `Generate ${roundName(last.size / 2).toLowerCase()}`;
  }
  return out;
}

// ---------------------------------------------------------------------------
export function planNextStage(tournament, matches, { idGen }) {
  const progress = tournamentProgress(tournament, matches);
  if (!progress.canAdvance) {
    return { ok: false, error: progress.needsWinner.length ? "A knockout match ended tied. Choose its winner first." : "The current stage isn't finished yet." };
  }
  const stages = tournament.stages;
  const byId = new Map(matches.map((m) => [m.id, m]));
  const last = stages[stages.length - 1];

  let first;
  if (last.kind === "knockout") {
    const participants = last.entries.map((e) => (e.type === "bye" ? e.teamId : matchOutcome(byId.get(e.matchId)).decidedWinnerId));
    first = knockoutNextRound(participants);
  } else {
    // seed the qualifiers: group winners first (best record first), then runners-up in the SAME group order
    const adv = tournament.format.advance;
    const tables = stages.filter((s) => s.kind === "group").map((s) => ({ s, rows: computeStandings(s.teamIds, stageMatchIds(s).map((id) => byId.get(id)).filter(Boolean)) }));
    const rank = (t) => t.rows[0];
    tables.sort((x, y) => rank(y).points - rank(x).points || rank(y).nrr - rank(x).nrr || x.s.name.localeCompare(y.s.name));
    const seeds = [];
    for (let pos = 0; pos < adv; pos++) tables.forEach((t) => t.rows[pos] && seeds.push(t.rows[pos].teamId));
    const groupOf = {};
    stages.filter((s) => s.kind === "group").forEach((s) => s.teamIds.forEach((id) => (groupOf[id] = s.name)));
    first = knockoutFirstRound(seeds);
    first = { ...first, entries: avoidSameGroup(first.entries, (id) => groupOf[id]) };
  }
  const { drafts, stage } = knockoutStage(first, idGen, roundName(first.size));
  return { ok: true, stages: [stage], drafts };
}

// Points tables to show: one for a league, one per group, none for knockouts.
export function tournamentTables(tournament, matches) {
  const byId = new Map(matches.map((m) => [m.id, m]));
  const stages = tournament.stages || [];
  const rowsFor = (teamIds, stage) => computeStandings(teamIds, stageMatchIds(stage).map((id) => byId.get(id)).filter(Boolean));
  const out = [];
  stages.forEach((s) => {
    if (s.kind === "league") out.push({ title: "Points table", rows: rowsFor(tournament.teamIds, s) });
    if (s.kind === "group") out.push({ title: s.name, rows: rowsFor(s.teamIds, s) });
  });
  return out;
}
